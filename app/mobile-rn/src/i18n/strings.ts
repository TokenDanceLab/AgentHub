export type AgentHubStrings = Record<keyof typeof strings.en, string>;

export function resolveAgentHubLocale(languageTag?: string): AgentHubLocale {
  return languageTag?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function getSystemLocale(): AgentHubLocale {
  return resolveAgentHubLocale(getLocales()[0]?.languageTag);
}

export function useStrings(): AgentHubStrings {
  return useMemo(() => strings[getSystemLocale()] as AgentHubStrings, []);
}
